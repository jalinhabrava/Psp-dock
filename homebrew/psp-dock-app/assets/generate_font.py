"""Bake small DejaVu Sans glyphs into a PSP-friendly 4-bit alpha atlas.

Requires Pillow and an installed DejaVu font, but not at PSP build time.
Only the rasterized glyphs are shipped; no TTF is copied into the game.
"""
from __future__ import annotations

import os
from pathlib import Path

from PIL import ImageFont


HERE = Path(__file__).resolve().parent
CHARACTERS = [chr(i) for i in range(32, 127)] + list("ÁÉÍÓÚÑÜáéíóúñü¿¡")


def font_path(name: str) -> Path:
    for root in (
        os.getenv("PSP_DOCK_FONT_ROOT", ""),
        "/usr/share/fonts/truetype/dejavu",
        "/usr/local/share/fonts",
        "C:/Windows/Fonts",
    ):
        path = Path(root) / name
        if path.is_file():
            return path
    raise FileNotFoundError(f"Install DejaVu fonts to generate {name}")


def bake(name: str, size: int, header: list[str]) -> None:
    font = ImageFont.truetype(str(font_path(name)), size)
    label = "body" if size == 12 else "heading"
    glyphs: list[str] = []
    pixels: list[int] = []
    for char in CHARACTERS:
        mask, (left, top) = font.getmask2(char, mode="L", anchor="ls")
        width, height = mask.size
        advance = round(font.getlength(char))
        offset = len(pixels)
        # Each glyph starts on a byte boundary; 4-bit coverage per pixel.
        data = list(mask)
        pixels.extend(
            (round(data[i] * 15 / 255) if i < len(data) else 0) |
            ((round(data[i + 1] * 15 / 255) if i + 1 < len(data) else 0) << 4)
            for i in range(0, len(data), 2)
        )
        glyphs.append(
            "    {%d, %d, %d, %d, %d, %d, %d}," %
            (ord(char), offset, width, height, left, top, advance)
        )
    header.append(f"static const UiGlyph ui_{label}_glyphs[] = {{")
    header.extend(glyphs)
    header.append("};")
    header.append(f"static const uint8_t ui_{label}_pixels[] = {{")
    for start in range(0, len(pixels), 24):
        header.append("    " + ", ".join(f"0x{v:02x}" for v in pixels[start:start + 24]) + ",")
    header.append("};")
    header.append(f"static const UiFont ui_{label}_font = {{")
    header.append(f"    ui_{label}_glyphs, ui_{label}_pixels, {len(glyphs)}")
    header.append("};")


def main() -> None:
    output = [
        "/* Generated by assets/generate_font.py from DejaVu Sans. Do not hand-edit. */",
        "/* Glyph alpha is 4-bit, packed low nibble first. */",
        "/* Include only after UiGlyph and UiFont have been declared. */",
        "#ifndef PSP_DOCK_UI_FONT_DATA_H",
        "#define PSP_DOCK_UI_FONT_DATA_H",
    ]
    bake("DejaVuSans.ttf", 12, output)
    bake("DejaVuSans-Bold.ttf", 20, output)
    output.append("#endif")
    (HERE.parent / "ui_font_data.h").write_text("\n".join(output) + "\n", encoding="ascii")
    print("Wrote PSP bitmap glyph atlas")


if __name__ == "__main__":
    main()
