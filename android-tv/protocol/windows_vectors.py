#!/usr/bin/env python3
"""Generate/check Android wire fixtures using the actual, current Windows host decoder/encoder.

No USB access. This is intentionally executed by CI when the Windows contract changes.
"""
from __future__ import annotations
import argparse
import binascii
import dataclasses
import os
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
os.environ['PSP_DOCK_TEST_NO_REAL_USB'] = '1'
sys.path.insert(0, str(ROOT))
from psp_dock.devices import native_dock as native

TARGET = ROOT / 'android-tv/app/src/test/resources/pdk2-windows.tsv'
SESSION = '0102030405060708090a0b0c0d0e0f10'


def frame(*, firmware=0x0308, phase=2, flags=21, sequence=1, result=2, activity=None,
          unit=0, done=0, total=0, transport=0, capabilities=None, build=None):
    if activity is None:
        activity = native.PHASE_ACTIVITIES.get(phase, (0,))[0] if flags & 16 else 0
    return b'\0' + native.FRAME.pack(b'PDK2', 3, 1, phase, flags, bytes.fromhex(SESSION), sequence, result) + native.EXTENSION.pack(
        b'NAT3', firmware, native.FIRMWARE_CAPABILITIES.get(firmware, 7) if capabilities is None else capabilities,
        native.FIRMWARE_BUILDS.get(firmware, (firmware << 16) | 1) if build is None else build,
        activity, unit, transport, done, total)


def fingerprint(s):
    flags = sum(bit for bit, field in [(1,'connected'),(2,'pending'),(4,'sony_storage'),(8,'exit_requested'),
        (16,'host_confirmed'),(32,'shutdown_requested'),(64,'ui_sounds_ready')] if getattr(s,field))
    return '|'.join(map(str,[s.firmware_revision,s.capabilities,s.build_id,s.phase,s.sequence,s.result,s.session,
        s.activity,s.unit,s.completed,s.total,s.transport_word,flags]))


def generate():
    rows = ['# Generated by protocol/windows_vectors.py from current psp_dock/devices/native_dock.py',
            '# kind\tname\twire_hex_without_report_id\texpected_or_command_arguments']
    statuses = [(f'firmware_{revision:04x}', frame(firmware=revision)) for revision in native.FIRMWARE_BUILDS]
    statuses += [
        ('unclaimed',frame(phase=1,flags=5,sequence=0,result=0)),
        ('choosing',frame(phase=1,activity=2)),('max_sequence',frame(sequence=0xffffffff)),
        ('max_progress',frame(phase=3,unit=1,done=2**64-2,total=2**64-1)),
        ('sounds_ready',frame(flags=85)),('transport_diagnostic',frame(transport=0xfff9)),
        ('terminal_shutdown',frame(phase=5,flags=53)),('pending',frame(flags=23,result=1)),
        ('negative_result',frame(result=-6)),('error_phase',frame(phase=255,activity=253,unit=255)),
        ('retired_0302',frame(firmware=0x0302)),('bad_build',frame(build=0x03080002)),
        ('bad_caps',frame(capabilities=7)),('bad_flag',frame(flags=149)),
        ('old_sound_flag',frame(firmware=0x0307,flags=85)),('old_transport',frame(firmware=0x0305,transport=1)),
        ('bad_drop_reason',frame(transport=10)),('pending_without_sequence',frame(flags=23,sequence=0,result=1)),
        ('wrong_pending_result',frame(flags=23,result=2)),('wrong_terminal_phase',frame(flags=53)),
        ('old_shutdown_cap',frame(firmware=0x0304,phase=5,flags=53)),
        ('unclaimed_progress',frame(phase=1,flags=5,sequence=0,result=0,activity=1)),
        ('bad_activity',frame(phase=3,activity=1)),('unknown_progress_with_total',frame(total=1)),
        ('progress_past_total',frame(phase=3,unit=1,done=2,total=1)),
        ('old_32_bytes',frame()[:33]),('wrong_report_prefix',b'\1'+frame()[1:]),
        ('empty_session',frame()[:9]+bytes(16)+frame()[25:]),
    ]
    for name,report in statuses:
        try: expected=fingerprint(native.decode_status(report))
        except native.NativeDockError: expected='reject'
        # Report-ID validation belongs to each platform transport; Android has no leading ID.
        if name=='wrong_report_prefix': continue
        rows.append('\t'.join(('status',name,report[1:].hex(),expected)))
    for name,op,phase,activity,unit,done,total in [
        ('begin',3,1,0,0,0,0),('controller',2,2,0,0,0,0),('choosing',4,1,2,0,0,0),
        ('progress_unsigned',4,3,4,1,2**64-2,2**64-1),('shutdown_encoding_only',5,5,0,0,0,0),
    ]:
        payload=native.encode_command(SESSION,17,phase,op,activity=activity,unit=unit,completed=done,total=total)[1:]
        spec='|'.join(map(str,[SESSION,17,phase,op,native.REVISION,native.BUILD_ID,activity,unit,done,total]))
        rows.append('\t'.join(('command',name,payload.hex(),spec)))
        token=0xa5
        fragments=[bytes((0xc0|i,token))+payload[2*i:2*i+2] for i in range(32)]
        crc=binascii.crc_hqx(payload,0xffff)
        fragments.append(bytes((0xe0,token,crc&255,crc>>8)))
        rows.append('\t'.join(('output',name,b''.join(fragments).hex(),payload.hex()+'|'+str(token))))
    return '\n'.join(rows)+'\n'


if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    expected=generate()
    if args.check:
        if not TARGET.is_file() or TARGET.read_text()!=expected:
            raise SystemExit('Windows/Android protocol fixtures drifted; regenerate and review Kotlin parity.')
        print('Windows/Android wire vectors match current source')
    else:
        TARGET.parent.mkdir(parents=True,exist_ok=True);TARGET.write_text(expected)
        print('Generated',len(expected.splitlines())-2,'Windows wire vectors')
