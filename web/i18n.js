  const reverse = new Map(Object.entries(translations).map(([es, en]) => [en, es]));
  const originalNodes = new WeakMap();
  const originalAttributes = new WeakMap();
  let current = 'en';
  let mode = 'auto';
  let observer;
  let processing = false;
  function detect() {
    const locales = Array.isArray(navigator.languages) && navigator.languages.length ? navigator.languages : [navigator.language || 'en'];
    const preferred = String(locales[0] || 'en').toLowerCase();
    return preferred === 'es' || preferred.startsWith('es-') ? 'es' : 'en';
  }
  function translate(value) {
    if (current === 'es' || typeof value !== 'string') return value;
    if (Object.hasOwn(translations, value)) return translations[value];
    for (const [pattern, replacer] of patterns) if (pattern.test(value)) return value.replace(pattern, replacer);
    return value;
  }
  function excluded(node) {
    const parent = node.nodeType === 1 ? node : node.parentElement;
    return !parent || !!parent.closest('[data-i18n-skip], script, style, pre, code, textarea, #game-title, #game-track, #game-meta, #xmb-game-background, #xmb-game-overlay, #transfer-list, #transfer-progress-file, #dock-connect-diagnostics-text, #dock-session-diagnostics-text, #storage-location-current, .xmb-ic');
  }
  function textNode(node) {
    if (excluded(node)) return;
    let original = originalNodes.get(node);
    const raw = node.nodeValue || '';
    if (original === undefined || raw !== original && raw !== translate(original)) {
      original = reverse.get(raw) || raw;
      originalNodes.set(node, original);
    }
    const replacement = current === 'es' ? original : translate(original);
    if (raw !== replacement) node.nodeValue = replacement;
  }
  const attributes = ['aria-label', 'title', 'placeholder'];
  function elementAttrs(element) {
    if (excluded(element)) return;
    let stored = originalAttributes.get(element);
    if (!stored) { stored = new Map(); originalAttributes.set(element, stored); }
    for (const attr of attributes) {
      if (!element.hasAttribute(attr)) continue;
      const raw = element.getAttribute(attr);
      let original = stored.get(attr);
      if (original === undefined || raw !== original && raw !== translate(original)) {
        original = reverse.get(raw) || raw;
        stored.set(attr, original);
      }
      const next = current === 'es' ? original : translate(original);
      if (raw !== next) element.setAttribute(attr, next);
    }
  }
  function visit(node) {
    if (node.nodeType === Node.TEXT_NODE) { textNode(node); return; }
    if (node.nodeType !== Node.ELEMENT_NODE || excluded(node)) return;
    elementAttrs(node);
    for (const child of node.childNodes) visit(child);
  }
  function apply() {
    if (!document.body) return;
    processing = true;
    try {
      document.documentElement.lang = current;
      for (const child of document.body.childNodes) visit(child);
    } finally { processing = false; }
  }
  function setLanguage(value) {
    mode = ['es', 'en'].includes(value) ? value : 'auto';
    current = mode === 'auto' ? detect() : mode;
    try { localStorage.setItem(STORAGE_KEY, mode); } catch { /* private mode */ }
    apply();
    document.dispatchEvent(new CustomEvent('dock-language-change', { detail: { language: current, mode } }));
  }
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (['es', 'en'].includes(saved)) mode = saved;
  } catch { /* private mode */ }
  current = mode === 'auto' ? detect() : mode;
  function start() {
    apply();
    observer = new MutationObserver((mutations) => {
      if (processing) return;
      processing = true;
      try {
        for (const mutation of mutations) {
          if (mutation.type === 'characterData') textNode(mutation.target);
          else if (mutation.type === 'attributes') elementAttrs(mutation.target);
          else for (const node of mutation.addedNodes) visit(node);
        }
      } finally { processing = false; }
    });
    observer.observe(document.body, { subtree: true, childList: true, characterData: true, attributes: true, attributeFilter: attributes });
  }
  window.DockI18n = Object.freeze({ locale: () => current, mode: () => mode, setLanguage, translate, apply, detect });
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', start, { once: true });
  else start();
